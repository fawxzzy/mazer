// Generates stub-app.sql from the LIVE capture (../preimage.json), never from the repository.
// Usage: node make-stub.mjs > stub-app.sql
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const pre = JSON.parse(readFileSync(join(here, '..', 'preimage.json'), 'utf8'));
const WANT = {
  mazer_leaderboard_page: '57b52e11c3aa16d5d9672e43c056b486',
  mazer_leaderboard_self_rank: '7f4912db0e015d565a88383e8610e86e',
};
const body = (name) => {
  const f = pre.functions.find((x) => x.name === name);
  const m = f.functiondef.match(/AS \$function\$([\s\S]*)\$function\$\s*$/);
  const src = m[1];
  const md5 = createHash('md5').update(src).digest('hex');
  if (md5 !== f.md5_prosrc || md5 !== WANT[name] || src.length !== f.prosrc_len || src.includes('\r')) {
    throw new Error(`live body of ${name} does not reproduce the captured md5/len (${md5})`);
  }
  return src;
};
const colSql = pre.profiles_table.columns
  .map((c) => `  ${c.c} ${c.t}${c.n === 'NO' ? ' not null' : ''}${c.d ? ` default ${c.d}` : ''}`)
  .join(',\n');

console.log(`-- GENERATED by make-stub.mjs from preimage.json (live capture ${pre.captured_at_utc}). Runs as postgres (the production runner).
-- Assumptions NOT in the capture: schema usage grants, mazer_progression_states columns, the body of the existing
-- username-origin trigger function (its live definition was not captured; modelled on the repo), RLS not FORCEd,
-- the 7 profile writer functions (not captured; the migration does not reference them, so they are not stubbed).
create schema mazer;
grant usage on schema mazer to anon, authenticated, service_role, supabase_auth_admin;

create table mazer.mazer_profiles (
${colSql},
  primary key (user_id)
);
create unique index mazer_profiles_username_unique_idx on mazer.mazer_profiles (lower(username));
create table mazer.mazer_progression_states (
  user_id uuid primary key,
  player_level bigint not null default 1,
  level_reached_at timestamptz
);

-- live table ACL {postgres=arwdDxtm/postgres,authenticated=arw/postgres}; column ACL username -> supabase_auth_admin=r
revoke all on mazer.mazer_profiles from public, anon, authenticated, service_role;
grant select, insert, update on mazer.mazer_profiles to authenticated;
grant select (username) on mazer.mazer_profiles to supabase_auth_admin;
revoke all on mazer.mazer_progression_states from public, anon, authenticated, service_role;

alter table mazer.mazer_profiles enable row level security;
create policy "Mazer Auth hook can inspect usernames" on mazer.mazer_profiles for select to supabase_auth_admin using (true);
create policy mazer_profiles_owner_insert_r001 on mazer.mazer_profiles for insert to authenticated
  with check (( SELECT auth.uid() AS uid) = user_id);
create policy mazer_profiles_owner_select_r001 on mazer.mazer_profiles for select to authenticated
  using (( SELECT auth.uid() AS uid) = user_id);
create policy mazer_profiles_owner_update_r001 on mazer.mazer_profiles for update to authenticated
  using (( SELECT auth.uid() AS uid) = user_id) with check (( SELECT auth.uid() AS uid) = user_id);

-- the one live user trigger on mazer_profiles (function body modelled on the repo; not captured live)
create function mazer.mazer_enforce_username_origin() returns trigger language plpgsql set search_path = '' as
$f$ begin
  if tg_op = 'UPDATE' then
    if new.username is distinct from old.username then new.username_origin := 'claimed'; else new.username_origin := old.username_origin; end if;
  end if;
  return new;
end; $f$;
create trigger ${pre.profiles_table.triggers[0]} before update of username, username_origin
  on mazer.mazer_profiles for each row execute function mazer.mazer_enforce_username_origin();

-- the two LIVE function bodies, byte for byte from the capture (LF, 0 CR), md5 re-verified by the generator
create function mazer.mazer_leaderboard_page(p_limit integer DEFAULT 25, p_offset integer DEFAULT 0)
 RETURNS TABLE(rank text, username text, player_level text, is_requesting_user boolean)
 LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO ''
AS $function$${body('mazer_leaderboard_page')}$function$;
create function mazer.mazer_leaderboard_self_rank()
 RETURNS TABLE(rank text, player_level text, has_username boolean)
 LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO ''
AS $function$${body('mazer_leaderboard_self_rank')}$function$;
-- live ACLs {postgres,anon,authenticated} and {postgres,authenticated}
revoke all on function mazer.mazer_leaderboard_page(integer, integer) from public;
grant execute on function mazer.mazer_leaderboard_page(integer, integer) to anon;
grant execute on function mazer.mazer_leaderboard_page(integer, integer) to authenticated;
revoke all on function mazer.mazer_leaderboard_self_rank() from public;
grant execute on function mazer.mazer_leaderboard_self_rank() to authenticated;

do $v$ begin
  if md5((select prosrc from pg_proc where oid='mazer.mazer_leaderboard_page(integer,integer)'::regprocedure)) <> '${WANT.mazer_leaderboard_page}'
  or md5((select prosrc from pg_proc where oid='mazer.mazer_leaderboard_self_rank()'::regprocedure)) <> '${WANT.mazer_leaderboard_self_rank}'
  then raise exception 'stub live-body md5 mismatch'; end if;
end $v$;`);
