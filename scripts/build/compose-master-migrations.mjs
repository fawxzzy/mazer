import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const migrationsRoot = path.join(repoRoot, 'supabase', 'migrations');

const sourcePath = (name) => path.join(migrationsRoot, name);
const readSource = (name) => readFileSync(sourcePath(name), 'utf8').replace(/\r\n/g, '\n').trim();
const bindMasterSchema = (sql) => sql
  .replace(/\bpublic\./g, 'mazer.')
  .replaceAll('set search_path = public', "set search_path = ''");

const requireMasterTables = `do $preflight$
begin
  if to_regnamespace('mazer') is null then
    raise exception 'MAZER_MASTER_SCHEMA_MISSING';
  end if;

  if to_regclass('mazer.mazer_profiles') is null
    or to_regclass('mazer.mazer_progression_states') is null
    or to_regclass('mazer.mazer_ai_progression_states') is null
    or to_regclass('mazer.mazer_cycle_receipts') is null
  then
    raise exception 'MAZER_MASTER_TABLES_INCOMPLETE';
  end if;
end;
$preflight$;`;

const forceOwnerIsolation = `alter table mazer.mazer_profiles enable row level security;
alter table mazer.mazer_profiles force row level security;
alter table mazer.mazer_progression_states enable row level security;
alter table mazer.mazer_progression_states force row level security;
alter table mazer.mazer_ai_progression_states enable row level security;
alter table mazer.mazer_ai_progression_states force row level security;
alter table mazer.mazer_cycle_receipts enable row level security;
alter table mazer.mazer_cycle_receipts force row level security;`;

const foundationSource = readSource('20260822000000_mazer_endless_progression_foundation.sql');
const foundationBodyStart = foundationSource.indexOf('-- 1. Replace both 1-99');
if (foundationBodyStart < 0) {
  throw new Error('Endless progression foundation marker is missing.');
}

const schemaParity = `-- Generated by scripts/build/compose-master-migrations.mjs.
-- Additive parity migration for the authoritative master project only:
-- bxtcuhkotumitoqtrcej / schema mazer.
-- It deliberately fails closed when the pre-existing master tables are absent.

${requireMasterTables}

${bindMasterSchema(readSource('20260716205924_account_state_revisions.sql'))}

${bindMasterSchema(readSource('20260821000000_mazer_profile_username.sql'))}

${bindMasterSchema(foundationSource.slice(foundationBodyStart))}

${forceOwnerIsolation}

alter function mazer.mazer_is_username_available(text) owner to postgres;
revoke all on function mazer.mazer_is_username_available(text) from public, anon, service_role;
grant execute on function mazer.mazer_is_username_available(text) to authenticated;
`;

const completionRpc = bindMasterSchema(readSource('20260822000100_mazer_endless_completion_rpc.sql'));
let leaderboardRpc = bindMasterSchema(readSource('20260822000200_mazer_leaderboard_rpc.sql'));
leaderboardRpc = leaderboardRpc.replace(
  'grant execute on function mazer.mazer_leaderboard_page(integer, integer) to authenticated;',
  'revoke all on function mazer.mazer_leaderboard_page(integer, integer) from anon;\n' +
    'grant execute on function mazer.mazer_leaderboard_page(integer, integer) to anon, authenticated;'
);
leaderboardRpc = leaderboardRpc.replace(
  'grant execute on function mazer.mazer_leaderboard_self_rank() to authenticated;',
  'revoke all on function mazer.mazer_leaderboard_self_rank() from anon;\n' +
    'grant execute on function mazer.mazer_leaderboard_self_rank() to authenticated;'
);

const runtimeContracts = `-- Generated by scripts/build/compose-master-migrations.mjs.
-- Server-authoritative progression and public-leaderboard capabilities for
-- bxtcuhkotumitoqtrcej / schema mazer. Apply only after schema parity.

${requireMasterTables}

${completionRpc}

${leaderboardRpc}

grant usage on schema mazer to anon, authenticated, service_role;

alter function mazer.mazer_initialize_progression(uuid) owner to postgres;
alter function mazer.mazer_complete_level(bigint, uuid, text, integer, integer, uuid, text, integer, text, timestamp with time zone, jsonb) owner to postgres;
alter function mazer.mazer_complete_ai_level(uuid, text, integer, integer, uuid, text, integer, text, timestamp with time zone, jsonb) owner to postgres;
alter function mazer.mazer_reset_progression(bigint, uuid) owner to postgres;
alter function mazer.mazer_leaderboard_page(integer, integer) owner to postgres;
alter function mazer.mazer_leaderboard_self_rank() owner to postgres;

revoke insert, update on table mazer.mazer_progression_states from authenticated;
revoke insert, update on table mazer.mazer_ai_progression_states from authenticated;
revoke insert on table mazer.mazer_cycle_receipts from authenticated;

${forceOwnerIsolation}
`;

const signupSource = bindMasterSchema(
  readSource('20260824140215_mazer_signup_username_claim.sql')
).replace(
  'grant usage on schema public to supabase_auth_admin;',
  'grant usage on schema mazer to supabase_auth_admin;'
).replace('public profile', 'Mazer profile');

const signupContracts = `-- Generated by scripts/build/compose-master-migrations.mjs.
-- Shared-project Mazer signup authority for bxtcuhkotumitoqtrcej / schema mazer.
-- The SQL function and auth.users trigger are installed here; selecting the
-- Before User Created hook remains a separately verified provider setting.

${requireMasterTables}

${signupSource}

alter function mazer.mazer_before_user_created(jsonb) owner to postgres;
alter function mazer.mazer_claim_signup_username() owner to postgres;
`;

const outputs = new Map([
  ['20260824170156_mazer_master_schema_parity.sql', schemaParity],
  ['20260824170159_mazer_master_runtime_contracts.sql', runtimeContracts],
  ['20260824170202_mazer_master_signup_username_claim.sql', signupContracts]
]);

const checkOnly = process.argv.includes('--check');
let changed = false;
for (const [name, contents] of outputs) {
  const target = sourcePath(name);
  const normalized = `${contents.trim()}\n`;
  if (checkOnly) {
    const current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
    if (current !== normalized) {
      changed = true;
      console.error(`Generated migration drift: ${name}`);
    }
  } else {
    writeFileSync(target, normalized, 'utf8');
  }
}

if (changed) {
  process.exitCode = 1;
}
